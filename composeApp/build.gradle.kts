// ─────────────────────────────────────────────────────────────────────────────
// Build-time config. Values come from the git-ignored `local.properties`
// (or environment variables in CI). Firebase *web* config is public by design
// (it ships to every browser) — it is kept out of git so the repo stays clean,
// and access is protected by Firestore Security Rules + API-key restrictions.
// Real secrets (Razorpay key secret, Anthropic API key) live only in Cloud
// Functions Secret Manager and never reach this build.
// ─────────────────────────────────────────────────────────────────────────────
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun cfg(key: String, env: String): String = localProps.getProperty(key)?.trim().orEmpty().ifEmpty { System.getenv(env).orEmpty() }

val relayConfig: Map<String, String> = linkedMapOf(
    "firebaseApiKey" to cfg("firebase.apiKey", "RELAY_FIREBASE_API_KEY"),
    "firebaseAuthDomain" to cfg("firebase.authDomain", "RELAY_FIREBASE_AUTH_DOMAIN"),
    "firebaseProjectId" to cfg("firebase.projectId", "RELAY_FIREBASE_PROJECT_ID"),
    "firebaseStorageBucket" to cfg("firebase.storageBucket", "RELAY_FIREBASE_STORAGE_BUCKET"),
    "firebaseMessagingSenderId" to cfg("firebase.messagingSenderId", "RELAY_FIREBASE_MESSAGING_SENDER_ID"),
    "firebaseAppId" to cfg("firebase.appId", "RELAY_FIREBASE_APP_ID"),
    "razorpayKeyId" to cfg("razorpay.keyId", "RELAY_RAZORPAY_KEY_ID"),
    "useEmulators" to cfg("relay.useEmulators", "RELAY_USE_EMULATORS").ifEmpty { "false" },
)

val generatedConfigDir = layout.buildDirectory.dir("generated/relayConfig/kotlin")

val generateRelayConfig by tasks.registering {
    description = "Generates RelayConfig.kt from local.properties / environment."
    val values = relayConfig
    val outDir = generatedConfigDir
    inputs.properties(values)
    outputs.dir(outDir)
    doLast {
        val required = values.filterKeys { it.startsWith("firebase") }
        val missing = required.filterValues { it.isBlank() }.keys
        if (missing.isNotEmpty()) {
            throw GradleException(
                "Missing Firebase config: $missing. Copy local.properties.example to local.properties and fill it in."
            )
        }
        fun esc(s: String) = s.replace("\\", "\\\\").replace("\"", "\\\"")
        val body = buildString {
            appendLine("// GENERATED by :composeApp:generateRelayConfig — do not edit, do not commit.")
            appendLine("package app.relay.config")
            appendLine()
            appendLine("internal object RelayConfig {")
            values.forEach { (k, v) ->
                if (k == "useEmulators") appendLine("    const val $k: Boolean = ${v.toBoolean()}")
                else appendLine("    const val $k: String = \"${esc(v)}\"")
            }
            appendLine("}")
        }
        val file = outDir.get().file("app/relay/config/RelayConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(body)
    }
}

